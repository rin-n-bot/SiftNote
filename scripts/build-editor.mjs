import { build } from "esbuild";
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { createRequire } from "node:module";
import { createHash } from "node:crypto";
const require = createRequire(import.meta.url);
const bundle = await build({
  entryPoints: ["src/editor/browser.ts"],
  bundle: true,
  write: false,
  format: "iife",
  platform: "browser",
  target: "chrome100",
  minify: true,
});
const fonts = [
  ["400", "400Regular", "Inter_400Regular", "normal"],
  ["500", "500Medium", "Inter_500Medium", "normal"],
  ["600", "600SemiBold", "Inter_600SemiBold", "normal"],
  ["700", "700Bold", "Inter_700Bold", "normal"],
  ["400", "400Regular_Italic", "Inter_400Regular_Italic", "italic"],
  ["700", "700Bold_Italic", "Inter_700Bold_Italic", "italic"],
];
let css = "";
const files = [];
for (const [weight, folder, file, style] of fonts) {
  const bytes = await readFile(
    require.resolve(`@expo-google-fonts/inter/${folder}/${file}.ttf`),
  );
  const hash = createHash("sha256").update(bytes).digest("hex").slice(0, 16);
  const name = `inter-${hash}.ttf`;
  files.push({
    name,
    contents: bytes.toString("base64"),
    encoding: "base64",
    byteLength: bytes.length,
  });
  css += `@font-face{font-family:Inter;font-weight:${weight};font-style:${style};src:url(${name}) format('truetype');font-display:swap;}`;
}
const script = bundle.outputFiles[0].text;
const scriptHash = createHash("sha256")
  .update(script)
  .digest("hex")
  .slice(0, 16);
const scriptName = `editor-${scriptHash}.js`;
files.push({
  name: scriptName,
  contents: script,
  encoding: "utf8",
  byteLength: Buffer.byteLength(script),
});
// CSS runs once when Tiptap creates the body. Editing/review reuse that node;
// backwards fill leaves no persistent opacity/transform or will-change hint.
css += `@keyframes note-body-enter{from{opacity:0;transform:translateY(-4px)}to{opacity:1;transform:translateY(0)}}@media(prefers-reduced-motion:no-preference){.tiptap{animation:note-body-enter 320ms ease-out backwards}}`;
const html = `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=5"><meta http-equiv="Content-Security-Policy" content="default-src 'none';script-src file:;style-src 'unsafe-inline';font-src file:;img-src file:;connect-src 'none';base-uri 'none';form-action 'none';"><style>${css}*{box-sizing:border-box}html,body{margin:0;background:var(--siftnote-background,#fff);color:#303546;font-family:Inter,sans-serif}body{padding:4px 20px 48px}.tiptap{min-height:calc(100vh - 56px);outline:none;font-size:16px;line-height:1.55;overflow-wrap:anywhere}.tiptap p{margin:0 0 14px}.tiptap h2{font-size:1.15em;font-weight:700;color:#181b28;margin:20px 0 8px}.tiptap h2:first-child{margin-top:4px}.tiptap ul,.tiptap ol{padding-left:24px;margin:8px 0 16px}.tiptap li p{margin-bottom:6px}.tiptap img{display:block;max-width:100%;height:auto;border-radius:12px;margin:12px 0}.tiptap p:first-child:last-child:empty:before{content:'Start writing your note…';color:#9da4b9;pointer-events:none;float:left;height:0}.source-flash{outline:2px solid #9bafca;outline-offset:3px;border-radius:3px}::selection{background:#c7dfff}strong{font-weight:700}</style></head><body><div id="editor"></div><script id="siftnote-startup" type="application/json">null</script><script src="${scriptName}"></script></body></html>`;
await mkdir("src/editor/generated", { recursive: true });
const version = createHash("sha256").update(html).digest("hex").slice(0, 16);
const htmlFile = {
  name: `editor-${version}.html`,
  contents: html,
  encoding: "utf8",
  byteLength: Buffer.byteLength(html),
};
await writeFile(
  "src/editor/generated/html.ts",
  `// Generated by npm run editor:bundle. Fully offline.\nexport const EDITOR_HTML = ${JSON.stringify(html)};\nexport const EDITOR_ENTRY = ${JSON.stringify(htmlFile.name)};\nexport const EDITOR_FILES = ${JSON.stringify(files).slice(0, -1)}, { name: ${JSON.stringify(htmlFile.name)}, contents: EDITOR_HTML, encoding: "utf8", byteLength: ${htmlFile.byteLength} }] as const;\n`,
);
console.log(
  `Bundled offline editor (${Math.round(Buffer.byteLength(html) / 1024)} KB HTML; six separate local Inter files).`,
);
